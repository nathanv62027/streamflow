"""#### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

# I used AI to write this code and learn how it works

# Define problem variables
L = 6
RA = 170
RB = 410
P1 = 100
q1 = 120
q2 = 120

# Define x and v variables
x = np.linspace(0, L, 500)
v = np.zeros_like(x)

# Calculate shear forces for all x's along beam length
for i in range(len(x)):
    pos = x[i]
    if pos < 2:
        v[i] = RA - (q1 * pos)
    elif 2 <= pos <= 4:
        v[i] = RA - (q1 * 2) - P1
    else:  # pos > 4
        v[i] = RA - (q1 * 2) - P1 + RB - (q2 * (pos - 4))

# Plot the shear diagram
plt.figure(figsize=(10, 6))

# Fill the space under the shear curve down to the zero line, format,
plt.fill_between(x, v, 0, color='blue', alpha=0.2)
plt.plot(x, v, color='blue')
plt.axhline(0, color='black', linestyle='--', linewidth=0.8)
plt.title('Shear Diagram')
plt.xlabel('x(ft)')
plt.ylabel('v (lb)')
plt.grid(True, linestyle=':', alpha=0.6)
plt.legend()

# Show diagram
plt.show()

