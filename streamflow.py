for i in range(len(x)):
    pos = x[i]
    if pos < 2:
        m[i] = RA * pos - (q1 * (pos**2) / 2)
    elif 2 < pos < 4:
        M2 = RA * 2 - (q1 * (2**2) / 2)
        m[i] = M2 + (RA - (q1 * 2) - P1) * (pos - 2)
    else:
        M2 = RA * 2 - (q1 * (2**2) / 2)
        M4 = M2 + (RA - (q1 * 2) - P1) * (4 - 2)
        m[i] = M4 + (RA - (q1 * 2) - P1 + RB) * (pos - 4) - (q2 * ((pos - 4)**2) / 2)

# Plot and format the bending moment diagram
